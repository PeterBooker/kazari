// yamlString quotes s as JSON, which YAML 1.2 reads as a double-quoted scalar.
func yamlString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSuffix(buf.String(), "\n")
}

type skillEntry struct {
	URI         string           `json:"uri"`
	Frontmatter skillFrontmatter `json:"frontmatter"`
	Resources   []skillFile      `json:"resources"`
}

type skillFile struct {
	URI    string `json:"uri"`
	Digest string `json:"digest"`
	Size   int    `json:"size"`
}

type skillsListParams struct {
	mcp.ParamsBase
	Cursor string `json:"cursor,omitempty"`
}

type skillsListResult struct {
	mcp.ResultBase
	mcp.Cacheable
	ResultType string       `json:"resultType,omitempty"`
	Skills     []skillEntry `json:"skills"`
}

// skillsTTL is how long clients may cache skills/list: the skill changes only on a
// restart with new configuration, and the digests catch a stale copy anyway.
const skillsTTL = 5 * time.Minute

type skillsGetParams struct {
	mcp.ParamsBase
	URI string `json:"uri"`
}

type skillsGetResult struct {
	mcp.ResultBase
	ResultType string     `json:"resultType,omitempty"`
	Skill      skillEntry `json:"skill"`
}

func (t texts) skillEntry() skillEntry {
	sum := sha256.Sum256([]byte(t.skill))
	return skillEntry{
		URI:         skillURI,
		Frontmatter: t.frontmatter,
		Resources:   []skillFile{{URI: skillURI, Digest: "sha256:" + hex.EncodeToString(sum[:]), Size: len(t.skill)}},
	}
}

// addSkill also adds get_guide for clients without the Skills extension.
func (b *builder) addSkill(s *mcp.Server, p auth.Principal) {
	s.AddResource(&mcp.Resource{
		URI:         skillURI,
		Name:        skillName,
		Title:       "Kazari guide",
		Description: b.text.frontmatter.Description,
		MIMEType:    skillMIME,
		Size:        int64(len(b.text.skill)),
	}, func(context.Context, *mcp.ReadResourceRequest) (*mcp.ReadResourceResult, error) {
		return &mcp.ReadResourceResult{Contents: []*mcp.ResourceContents{{URI: skillURI, MIMEType: skillMIME, Text: b.text.skill}}}, nil
	})

	entry := b.text.skillEntry()
	must(mcp.AddReceivingCustomMethod(s, "skills/list",
		func(context.Context, *mcp.ServerSession, *skillsListParams) (*skillsListResult, error) {
			return &skillsListResult{
				Cacheable:  mcp.Cacheable{TTLMs: int(skillsTTL / time.Millisecond), CacheScope: "private"},
				ResultType: "complete",
				Skills:     []skillEntry{entry},
			}, nil
		}))
	must(mcp.AddReceivingCustomMethod(s, "skills/get",
		func(_ context.Context, _ *mcp.ServerSession, params *skillsGetParams) (*skillsGetResult, error) {
			if params == nil || params.URI != skillURI {
				uri := ""
				if params != nil {
					uri = params.URI
				}
				return nil, &jsonrpc.Error{Code: jsonrpc.CodeInvalidParams, Message: fmt.Sprintf("no skill at %q; this server serves %s", uri, skillURI)}
			}
			return &skillsGetResult{ResultType: "complete", Skill: entry}, nil
		}))

	t := &mcp.Tool{
		Name:        "get_guide",
		Description: b.text.tools["get_guide"],
		Annotations: annotations("Get guide", true, false, true),
	}
	mcp.AddTool(s, t, func(ctx context.Context, _ *mcp.CallToolRequest, _ GuideInput) (res *mcp.CallToolResult, out any, err error) {
		defer b.recoverTool(ctx, t.Name, func(e error) { res, out, err = nil, nil, e })
		if err := requireScope(p, auth.ScopeRead); err != nil {
			return nil, nil, b.toolError(ctx, t.Name, err)
		}
		// Text only: a structured copy would double the size.
		return &mcp.CallToolResult{Content: []mcp.Content{&mcp.TextContent{Text: b.text.skill}}}, nil, nil
	})
}

// GuideInput is the (empty) input of get_guide.
type GuideInput struct{}

// must panics on errors only a programming mistake causes.
func must(err error) {
	if err != nil {
		panic(err)
	}
}

