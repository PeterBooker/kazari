// The instance's Agent Skill, served over MCP by the Skills extension
// (SEP-2640): the skill:// resource, skills/list and skills/get.
const (
	skillName       = "kazari"
	skillURI        = "skill://" + skillName + "/SKILL.md"
	skillMIME       = "text/markdown"
	skillsExtension = "io.modelcontextprotocol/skills"
)

// Skill returns the instance's Agent Skill: a SKILL.md generated from o, so
// it states the real limits, CSP and URL shapes. The MCP server serves it
// as skill://kazari/SKILL.md and through get_guide; the REST API serves the
// same text at GET /v1/skill.
func Skill(links present.Links, o Options) string {
	return newTexts(links, o.withDefaults(Deps{})).skill
}

// skillFrontmatter is the SKILL.md frontmatter, rendered once as YAML into
// the file and once as JSON into the skills/list entry, so the two agree.
type skillFrontmatter struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

func (t texts) skillDescription(o Options) string {
	base := o.BaseDomain
	if base == "" {
		base = "<base>"
	}
	return fmt.Sprintf("Publish, edit and retire static web pages (HTML artifacts) on the Kazari instance at %s through "+
		"its MCP tools. Use when the user asks to publish, share, host or change a page, report, dashboard or demo, or "+
		"mentions a %s URL or an artifact slug.", base, base)
}

// skillText renders SKILL.md: frontmatter, the workflow, editing, the
// authoring conventions with this instance's settings, and the errors.
func (t texts) skillText(o Options) string {
	var b strings.Builder
	// The name is a plain lower-case word; the description is quoted.
	fmt.Fprintf(&b, "---\nname: %s\ndescription: %s\n---\n\n# Kazari\n\n", t.frontmatter.Name, yamlString(t.frontmatter.Description))
	fmt.Fprintf(&b, "Kazari hosts static web pages. Each artifact has a permanent slug and is served at %s (the published "+
		"version) and at %s (version N, forever). This file is generated by the instance, so the limits and the policy "+
		"below are its real settings; the tool descriptions say the same.\n\n", t.pageURL, t.versionURL)

	if o.MCPURL != "" {
		b.WriteString("## Connect\n\n")
		fmt.Fprintf(&b, "Add `%s` as a remote MCP server (Streamable HTTP). Claude Code: `claude mcp add --transport http "+
			"kazari %s`, then sign in when asked, or add `--header \"Authorization: Bearer <API key>\"`.\n\n", o.MCPURL, o.MCPURL)
	}

	b.WriteString("## Workflow\n\n")
	fmt.Fprintf(&b, "1. **Publish a page:** `create_artifact` with `slug`, `name`, `description` and `files`. Report the "+
		"`url` from the result to the user.\n"+
		"2. **Change a page:** `read_file` with `anchors: true`, then `edit_file` with `expected_version` set to the "+
		"`latest_version` the read returned. `update_artifact` adds, replaces or deletes whole files.\n"+
		"3. **On `version_conflict` or `anchor_mismatch`:** read the file again and redo the edit against the new text. "+
		"Never resend a failed edit unchanged.\n"+
		"4. **Large content** (any file, or all files together, above %s): `begin_upload`, `upload_chunk` for each file, "+
		"then `create_artifact` or `update_artifact` with `upload_id`.\n"+
		"5. **Roll back:** `get_artifact` lists the versions; `publish_version` serves one again.\n"+
		"6. **Retire:** prefer `set_visibility` `\"unpublished\"` (reversible) or `mark_stale` (expires after a grace "+
		"period) to `delete_artifact`. Ask the user before `delete_artifact` with `hard: true`; clients that support it "+
		"also show the user a confirmation.\n\n", size(o.InlineGuidanceBytes))

	b.WriteString("## Editing a file\n\n")
	b.WriteString("`edit_file` changes one text file of the latest version and publishes the result as a new version; " +
		"every other file carries over. Only the changed text is sent.\n\n")
	fmt.Fprintf(&b, "- **Text edits** (the default): each edit has `old_text`, copied exactly from the file, and "+
		"`new_text`. `old_text` must match once: add surrounding lines to make it unique, or set `replace_all`. Edits "+
		"apply in order, each to the result of the one before.\n"+
		"- If `old_text` does not match exactly, whole lines are compared ignoring trailing whitespace, then ignoring "+
		"indentation, and `new_text` is re-indented to fit. Each edit's `match` in the result says which was used: "+
		"`exact`, `trailing_whitespace` or `indentation`. A miss names the closest lines with their anchors.\n"+
		"- **Anchor edits:** `read_file` with `anchors: true` prefixes every line with `<line>:<hash>|`, e.g. "+
		"`12:3fa0|<h1>Title</h1>`. An edit with `start` (and optionally `end`) replaces those lines, inclusive, with "+
		"`new_text`; an empty `new_text` deletes them. To insert, replace a line with itself plus the new lines. Every "+
		"anchor in one call refers to the file as read, and the ranges must not overlap. A line that changed since the "+
		"read fails with `anchor_mismatch`, so nothing is overwritten by mistake.\n"+
		"- One call takes text edits or anchor edits, at most %d.\n"+
		"- The result has the new `version` and, for each edit, `start_line`, `end_line` and an anchored `excerpt` of "+
		"the new text, so a follow-up anchor edit needs no new read. Lines longer than 160 bytes are clipped in "+
		"excerpts (\"…[+N bytes]\"): read the file before rewriting such a line whole.\n"+
		"- `edit_file` edits the latest version. `read_file` reads the published version unless given `version`; when "+
		"its `latest_version` differs from its `version` (after a rollback), read `version: latest_version` before "+
		"editing.\n\n", artifact.MaxEdits)

	b.WriteString("## Authoring conventions\n\n")
	fmt.Fprintf(&b, "- Build a self-contained `index.html`; it is served at %s. Extra files (CSS, JavaScript, images) are "+
		"fine.\n", t.pageURL)
	b.WriteString("- Use relative links (`about.html`, `assets/app.js`), never paths starting with `/`, so the page also " +
		"works on pinned version URLs.\n")
	fmt.Fprintf(&b, "- %s\n", t.csp)
	b.WriteString("- No server-side code: no PHP, API routes, databases or server build step. Ship the built output.\n")
	fmt.Fprintf(&b, "- %s On `slug_taken`, pick another.\n", t.slugRules)
	fmt.Fprintf(&b, "- %s\n- %s\n", t.limits, t.text)
	fmt.Fprintf(&b, "- %s\n\n", t.metadata)

	b.WriteString("## Errors\n\n")
	b.WriteString("A failed call returns `<code>: <message>`, and usually a `Next step:` line. Follow it.\n\n")
	b.WriteString("| Code | Next step |\n| ---- | --------- |\n")
	for _, code := range nextStepOrder {
		fmt.Fprintf(&b, "| `%s` | %s |\n", code, t.next[code])
	}
	return b.String()
}

// yamlString renders s as a YAML double-quoted scalar. A JSON string is
// one, since YAML 1.2 is a superset of JSON.
func yamlString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSuffix(buf.String(), "\n")
}

// skillEntry is a skill as skills/list and skills/get describe it.
type skillEntry struct {
	URI         string           `json:"uri"`
	Frontmatter skillFrontmatter `json:"frontmatter"`
	Resources   []skillFile      `json:"resources"`
}

// skillFile is one file of a skill with its digest and size.
type skillFile struct {
	URI    string `json:"uri"`
	Digest string `json:"digest"`
	Size   int    `json:"size"`
}

type skillsListParams struct {
	mcp.ParamsBase
	Cursor string `json:"cursor,omitempty"`
}

type skillsListResult struct {
	mcp.ResultBase
	mcp.Cacheable
	ResultType string       `json:"resultType,omitempty"`
	Skills     []skillEntry `json:"skills"`
}

// skillsTTL is how long a client may cache the skills list: the skill
// changes only when the server restarts with a new configuration, and the
// digests catch a stale copy anyway.
const skillsTTL = 5 * time.Minute

type skillsGetParams struct {
	mcp.ParamsBase
	URI string `json:"uri"`
}

type skillsGetResult struct {
	mcp.ResultBase
	ResultType string     `json:"resultType,omitempty"`
	Skill      skillEntry `json:"skill"`
}

func (t texts) skillEntry() skillEntry {
	sum := sha256.Sum256([]byte(t.skill))
	return skillEntry{
		URI:         skillURI,
		Frontmatter: t.frontmatter,
		Resources:   []skillFile{{URI: skillURI, Digest: "sha256:" + hex.EncodeToString(sum[:]), Size: len(t.skill)}},
	}
}

// addSkill serves the skill: its resource, skills/list, skills/get and the
// get_guide tool for clients without the extension.
func (b *builder) addSkill(s *mcp.Server, p auth.Principal) {
	s.AddResource(&mcp.Resource{
		URI:         skillURI,
		Name:        skillName,
		Title:       "Kazari guide",
		Description: b.text.frontmatter.Description,
		MIMEType:    skillMIME,
		Size:        int64(len(b.text.skill)),
	}, func(context.Context, *mcp.ReadResourceRequest) (*mcp.ReadResourceResult, error) {
		return &mcp.ReadResourceResult{Contents: []*mcp.ResourceContents{{URI: skillURI, MIMEType: skillMIME, Text: b.text.skill}}}, nil
	})

	entry := b.text.skillEntry()
	must(mcp.AddReceivingCustomMethod(s, "skills/list",
		func(context.Context, *mcp.ServerSession, *skillsListParams) (*skillsListResult, error) {
			return &skillsListResult{
				Cacheable:  mcp.Cacheable{TTLMs: int(skillsTTL / time.Millisecond), CacheScope: "private"},
				ResultType: "complete",
				Skills:     []skillEntry{entry},
			}, nil
		}))
	must(mcp.AddReceivingCustomMethod(s, "skills/get",
		func(_ context.Context, _ *mcp.ServerSession, params *skillsGetParams) (*skillsGetResult, error) {
			if params == nil || params.URI != skillURI {
				uri := ""
				if params != nil {
					uri = params.URI
				}
				return nil, &jsonrpc.Error{Code: jsonrpc.CodeInvalidParams, Message: fmt.Sprintf("no skill at %q; this server serves %s", uri, skillURI)}
			}
			return &skillsGetResult{ResultType: "complete", Skill: entry}, nil
		}))

	t := &mcp.Tool{
		Name:        "get_guide",
		Description: b.text.tools["get_guide"],
		Annotations: annotations("Get guide", true, false, true),
	}
	mcp.AddTool(s, t, func(ctx context.Context, _ *mcp.CallToolRequest, _ GuideInput) (res *mcp.CallToolResult, out any, err error) {
		defer b.recoverTool(ctx, t.Name, func(e error) { res, out, err = nil, nil, e })
		if err := requireScope(p, auth.ScopeRead); err != nil {
			return nil, nil, b.toolError(ctx, t.Name, err)
		}
		// Text only: the guide is for the model, and a structured copy
		// would double its size.
		return &mcp.CallToolResult{Content: []mcp.Content{&mcp.TextContent{Text: b.text.skill}}}, nil, nil
	})
}

// GuideInput is the (empty) input of get_guide.
type GuideInput struct{}

// must panics on an error that only a programming mistake can cause, such
// as registering a custom method under a standard method's name.
func must(err error) {
	if err != nil {
		panic(err)
	}
}

